-- One logical table, one partition per region. Keys of a partitioned table include the
-- partition key, so the primary key is (id, region).
CREATE TABLE visits (
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    region     text NOT NULL,
    clinic_id  integer NOT NULL REFERENCES clinics (id),
    patient_id integer NOT NULL REFERENCES patients (id),
    starts_at  timestamptz NOT NULL,
    status     text NOT NULL DEFAULT 'scheduled',
    notes      text,
    PRIMARY KEY (id, region)
) PARTITION BY LIST (region);

CREATE TABLE visits_eu PARTITION OF visits FOR VALUES IN ('eu');
CREATE TABLE visits_us PARTITION OF visits FOR VALUES IN ('us');

-- On the parent: every partition gets it, including the one attached below.
CREATE INDEX visits_patient_starts ON visits (patient_id, starts_at);

-- The import becomes the 'br' partition without copying a row. In production, add
-- CHECK (region = 'br') to visits_br first: ATTACH then skips the scan that proves it.
ALTER TABLE visits_br ADD CONSTRAINT visits_br_region CHECK (region = 'br');
ALTER TABLE visits ATTACH PARTITION visits_br FOR VALUES IN ('br');
ALTER TABLE visits_br DROP CONSTRAINT visits_br_region;

-- The identity starts at 1, but the import kept its old ids: move it past them.
SELECT setval(pg_get_serial_sequence('visits', 'id'), (SELECT max(id) FROM visits));
