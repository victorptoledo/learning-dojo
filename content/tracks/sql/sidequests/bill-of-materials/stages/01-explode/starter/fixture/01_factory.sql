-- A small bicycle factory. kind tells assemblies (built from other parts) from
-- components (bought). unit_cost is the standard cost of a component.
CREATE TABLE parts (
    id        integer PRIMARY KEY,
    sku       text NOT NULL UNIQUE,
    name      text NOT NULL,
    kind      text NOT NULL CHECK (kind IN ('assembly', 'component')),
    unit_cost numeric(10, 2)
);
-- One row per direct use: parent is built with quantity units of child.
CREATE TABLE bom (
    parent_id integer NOT NULL REFERENCES parts,
    child_id  integer NOT NULL REFERENCES parts,
    quantity  integer NOT NULL CHECK (quantity > 0),
    PRIMARY KEY (parent_id, child_id)
);
CREATE TABLE suppliers (id integer PRIMARY KEY, name text NOT NULL UNIQUE);
-- A supplier's price for a part from valid_from on, until its next row.
CREATE TABLE prices (
    part_id     integer NOT NULL REFERENCES parts,
    supplier_id integer NOT NULL REFERENCES suppliers,
    price       numeric(10, 2) NOT NULL,
    valid_from  date NOT NULL,
    PRIMARY KEY (part_id, supplier_id, valid_from)
);
CREATE TABLE stock (part_id integer PRIMARY KEY REFERENCES parts, on_hand integer NOT NULL);

