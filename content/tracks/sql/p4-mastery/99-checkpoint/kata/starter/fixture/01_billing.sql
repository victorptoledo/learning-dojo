-- The support screen calls search_customers(term) with whatever the agent typed.
CREATE FUNCTION search_customers(term text) RETURNS TABLE (id integer, name text)
LANGUAGE plpgsql AS $$
BEGIN
    RETURN QUERY EXECUTE
        'SELECT id, name FROM customers WHERE name ILIKE ''%' || term || '%'' ORDER BY id';
END
$$;
